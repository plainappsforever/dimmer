#!/usr/bin/env python3
"""Writes app/src/main/res/values-<qualifier>/strings.xml from scripts/l10n/<lang>.txt (v3.1.1 translations).

Source format (one string per line, UTF-8):  <name><TAB><text>   - "\\n" in the text = line break; lines starting with
"#" are comments. The text is plain: this script does the Android escaping (' " @ ? & <).
Checks (stops with an error): every translatable English string is present, no extra or non-translatable names,
the same format placeholders (%1$s, %2$d, %%) as English, and "Dimmer" kept wherever English has it.
Usage: python3 scripts/make-strings.py            (all languages)   or   python3 scripts/make-strings.py de ja
"""
import os, re, sys, xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EN = os.path.join(ROOT, "app/src/main/res/values/strings.xml")
# language file -> Android resource qualifier (Indonesian is "in" on Android, locale tag "id")
LANGS = {"de": "de", "es": "es", "pt-BR": "pt-rBR", "fr": "fr", "it": "it", "tr": "tr", "ru": "ru", "id": "in",
         "hi": "hi", "ja": "ja", "zh-CN": "zh-rCN", "ko": "ko", "ar": "ar", "vi": "vi"}

def unescape(s):
    return s.replace("\\n", "\n").replace("\\'", "'").replace('\\"', '"')

def escape(s):
    s = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    s = s.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if s[:1] in ("@", "?"):
        s = "\\" + s
    return s

root = ET.parse(EN).getroot()
english, order = {}, []
for e in root.iter("string"):
    if e.get("translatable") == "false":
        continue
    english[e.get("name")] = unescape(e.text or "")
    order.append(e.get("name"))

PH = re.compile(r"%(?:\d+\$)?[sd]|%%")
def placeholders(s):
    return sorted(PH.findall(s))

def build(lang):
    src = os.path.join(ROOT, "scripts/l10n", f"{lang}.txt")
    t, errors = {}, []
    for n, line in enumerate(open(src, encoding="utf-8"), 1):
        line = line.rstrip("\n")
        if not line.strip() or line.startswith("#"):
            continue
        if "\t" not in line:
            errors.append(f"{lang}.txt:{n}: no TAB"); continue
        k, v = line.split("\t", 1)
        if k in t:
            errors.append(f"{lang}.txt:{n}: duplicate {k}")
        t[k] = v.replace("\\n", "\n").strip()
    missing = [k for k in order if k not in t]
    extra = [k for k in t if k not in english]
    if missing: errors.append(f"{lang}: missing {missing}")
    if extra: errors.append(f"{lang}: extra / non-translatable {extra}")
    for k in order:
        if k not in t: continue
        if placeholders(t[k]) != placeholders(english[k]):
            errors.append(f"{lang}: {k}: placeholders {placeholders(t[k])} != English {placeholders(english[k])}")
        if "Dimmer" in english[k] and "Dimmer" not in t[k]:
            errors.append(f"{lang}: {k}: brand 'Dimmer' missing")
        if not t[k]:
            errors.append(f"{lang}: {k}: empty")
    if errors:
        raise SystemExit("\n".join(errors))
    out_dir = os.path.join(ROOT, "app/src/main/res", "values-" + LANGS[lang])
    os.makedirs(out_dir, exist_ok=True)
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             f"<!-- GENERATED by scripts/make-strings.py from scripts/l10n/{lang}.txt - edit that file, not this one. -->",
             "<resources>"]
    lines += [f'    <string name="{k}">{escape(t[k])}</string>' for k in order]
    lines.append("</resources>\n")
    open(os.path.join(out_dir, "strings.xml"), "w", encoding="utf-8").write("\n".join(lines))
    print(f"{lang:6} -> values-{LANGS[lang]}/strings.xml ({len(order)} strings)")

for lang in (sys.argv[1:] or LANGS):
    build(lang)

# res/xml/locales_config.xml (per-app language list, Android 13+) must name exactly these languages plus English.
cfg = open(os.path.join(ROOT, "app/src/main/res/xml/locales_config.xml"), encoding="utf-8").read()
listed = sorted(re.findall(r'<locale android:name="([^"]+)"', cfg))
expected = sorted(["en"] + list(LANGS))
if listed != expected:
    raise SystemExit(f"locales_config.xml lists {listed}, expected {expected}")
print(f"locales_config.xml: {len(listed)} languages, matches")
