// Dimmer app icon, drawn from primitives only (circles, strokes, gradients). No SF Symbols, no fonts, no stock art.
// Design: a warm disc on a dark night background; a soft gradient shades its right half, like a screen being dimmed
// (bright on the left, dark on the right, the same direction as the darkness slider). A thin warm ring keeps the
// shaded half's outline readable on any wallpaper.
//
// Usage (from the repo root):  swift scripts/make-icon.swift
// Writes, from ONE set of geometry constants below:
//   app/src/main/res/drawable/ic_launcher_{background,foreground,monochrome}.xml  adaptive-icon layers (vector, 108dp)
//   app/src/main/res/mipmap-{mdpi..xxxhdpi}/ic_launcher.png, ic_launcher_round.png  legacy icons (48dp)
//   dist/play/icon-512.png                                                     Play Store icon, 512x512, 32-bit RGBA, opaque
// The vectors and the PNGs use the same numbers, so the launcher and the store show the same picture.
import CoreGraphics
import Foundation
import ImageIO
import UniformTypeIdentifiers

// MARK: geometry, in the adaptive-icon viewport (108 x 108 units; the launcher shows roughly the centre 72 x 72)
let view: CGFloat = 108
let centre = CGPoint(x: 54, y: 54)
let discR: CGFloat = 23          // disc radius (diameter 46, well inside the 66-unit safe circle)
let ringW: CGFloat = 1.2          // ring stroke width, drawn on the disc edge
let bgCentre = CGPoint(x: 54, y: 40), bgR: CGFloat = 80
let bgInner: UInt32 = 0x2B1D15, bgOuter: UInt32 = 0x0B0908     // warm charcoal -> near black
let discLight: UInt32 = 0xFFC56E, discWarm: UInt32 = 0xFF8A2A   // amber, top-left -> bottom-right
let shadeColour: UInt32 = 0x0B0908
// Shade across the disc, left -> right: (position 0...1 across the disc, alpha). A smoothstep from 25 % to 95 %, sampled
// at 11 stops, so there is no visible band where the shade begins.
let shadeStops: [(CGFloat, CGFloat)] = (0...10).map { i in
  let t = CGFloat(i) / 10, x = min(max((t - 0.25) / 0.70, 0), 1)
  return (t, 0.93 * x * x * (3 - 2 * x))
}
let ringColour: UInt32 = 0xFFB257, ringAlpha: CGFloat = 0.75

// MARK: output paths
let root = URL(fileURLWithPath: CommandLine.arguments.count > 1 ? CommandLine.arguments[1] : FileManager.default.currentDirectoryPath)
let res = root.appendingPathComponent("app/src/main/res")
let play = root.appendingPathComponent("dist/play")
try FileManager.default.createDirectory(at: play, withIntermediateDirectories: true)
let space = CGColorSpace(name: CGColorSpace.sRGB)!

func rgb(_ h: UInt32, _ a: CGFloat = 1) -> CGColor {
  CGColor(colorSpace: space, components: [CGFloat((h >> 16) & 255) / 255, CGFloat((h >> 8) & 255) / 255, CGFloat(h & 255) / 255, a])!
}
func hex(_ h: UInt32, _ a: CGFloat = 1) -> String { String(format: "#%02X%06X", Int((a * 255).rounded()), h) }
func n(_ v: CGFloat) -> String { String(format: "%.2f", v) }

// MARK: vector drawables (adaptive layers)
let header = """
<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by scripts/make-icon.swift - edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
"""
func circlePath(_ c: CGPoint, _ r: CGFloat) -> String {
  "M\(n(c.x - r)),\(n(c.y))a\(n(r)),\(n(r)) 0,1 0,\(n(2 * r)),0a\(n(r)),\(n(r)) 0,1 0,\(n(-2 * r)),0z"
}
let disc = circlePath(centre, discR)
func shadeItems(_ colour: UInt32, alphaScale: (CGFloat) -> CGFloat) -> String {
  shadeStops.map { "                    <item android:offset=\"\(n($0.0))\" android:color=\"\(hex(colour, alphaScale($0.1)))\" />" }
    .joined(separator: "\n")
}
let background = header + """

    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="\(n(bgCentre.x))" android:centerY="\(n(bgCentre.y))"
                android:gradientRadius="\(n(bgR))" android:startColor="\(hex(bgInner))" android:endColor="\(hex(bgOuter))" />
        </aapt:attr>
    </path>
</vector>

"""
let foreground = header + """

    <path android:pathData="\(disc)">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="\(n(centre.x - discR))" android:startY="\(n(centre.y - discR))"
                android:endX="\(n(centre.x + discR))" android:endY="\(n(centre.y + discR))"
                android:startColor="\(hex(discLight))" android:endColor="\(hex(discWarm))" />
        </aapt:attr>
    </path>
    <path android:pathData="\(disc)">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="\(n(centre.x - discR))" android:startY="\(n(centre.y))"
                android:endX="\(n(centre.x + discR))" android:endY="\(n(centre.y))">
\(shadeItems(shadeColour) { $0 })
            </gradient>
        </aapt:attr>
    </path>
    <path android:pathData="\(disc)" android:fillColor="#00000000"
        android:strokeColor="\(hex(ringColour, ringAlpha))" android:strokeWidth="\(n(ringW))" />
</vector>

"""
// Monochrome (themed icons): only alpha counts. Ring at full strength; the disc fades out to the right.
let monochrome = header + """

    <path android:pathData="\(disc)">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="\(n(centre.x - discR))" android:startY="\(n(centre.y))"
                android:endX="\(n(centre.x + discR))" android:endY="\(n(centre.y))">
\(shadeItems(0xFFFFFF) { 1 - $0 })
            </gradient>
        </aapt:attr>
    </path>
    <path android:pathData="\(disc)" android:fillColor="#00000000"
        android:strokeColor="#FFFFFFFF" android:strokeWidth="\(n(ringW))" />
</vector>

"""
for (name, body) in [("background", background), ("foreground", foreground), ("monochrome", monochrome)] {
  let url = res.appendingPathComponent("drawable/ic_launcher_\(name).xml")
  try body.write(to: url, atomically: true, encoding: .utf8)
  print("wrote \(url.path.replacingOccurrences(of: root.path + "/", with: ""))")
}

// MARK: raster rendering of the same layers (legacy icons, Play icon)
enum Mask { case none, circle, roundedSquare }

/// Draws the icon onto a size x size canvas showing the viewport square `crop` (centre 72 units for launcher-style
/// icons). `opaque` = no alpha channel (Play Store icon).
func render(size: Int, crop: CGFloat, mask: Mask, opaque: Bool) -> CGImage {
  let info = opaque ? CGImageAlphaInfo.noneSkipLast.rawValue : CGImageAlphaInfo.premultipliedLast.rawValue
  let ctx = CGContext(data: nil, width: size, height: size, bitsPerComponent: 8, bytesPerRow: 0, space: space, bitmapInfo: info)!
  ctx.setShouldAntialias(true)
  ctx.interpolationQuality = .high
  // y down, viewport units
  ctx.translateBy(x: 0, y: CGFloat(size)); ctx.scaleBy(x: 1, y: -1)
  let s = CGFloat(size) / crop
  ctx.scaleBy(x: s, y: s)
  let o = (view - crop) / 2
  ctx.translateBy(x: -o, y: -o)
  let visible = CGRect(x: o, y: o, width: crop, height: crop)
  switch mask {
  case .none: break
  case .circle: ctx.addEllipse(in: visible); ctx.clip()
  case .roundedSquare:
    ctx.addPath(CGPath(roundedRect: visible.insetBy(dx: crop * 0.04, dy: crop * 0.04), cornerWidth: crop * 0.2, cornerHeight: crop * 0.2, transform: nil))
    ctx.clip()
  }
  // background
  let bg = CGGradient(colorsSpace: space, colors: [rgb(bgInner), rgb(bgOuter)] as CFArray, locations: [0, 1])!
  ctx.drawRadialGradient(bg, startCenter: bgCentre, startRadius: 0, endCenter: bgCentre, endRadius: bgR, options: [.drawsAfterEndLocation])
  // disc
  let discRect = CGRect(x: centre.x - discR, y: centre.y - discR, width: 2 * discR, height: 2 * discR)
  ctx.saveGState()
  ctx.addEllipse(in: discRect); ctx.clip()
  let warm = CGGradient(colorsSpace: space, colors: [rgb(discLight), rgb(discWarm)] as CFArray, locations: [0, 1])!
  ctx.drawLinearGradient(warm, start: CGPoint(x: discRect.minX, y: discRect.minY), end: CGPoint(x: discRect.maxX, y: discRect.maxY),
                         options: [.drawsBeforeStartLocation, .drawsAfterEndLocation])
  let shade = CGGradient(colorsSpace: space, colors: shadeStops.map { rgb(shadeColour, $0.1) } as CFArray,
                         locations: shadeStops.map { $0.0 })!
  ctx.drawLinearGradient(shade, start: CGPoint(x: discRect.minX, y: centre.y), end: CGPoint(x: discRect.maxX, y: centre.y),
                         options: [.drawsBeforeStartLocation, .drawsAfterEndLocation])
  ctx.restoreGState()
  // ring
  ctx.setStrokeColor(rgb(ringColour, ringAlpha)); ctx.setLineWidth(ringW)
  ctx.strokeEllipse(in: discRect)
  return ctx.makeImage()!
}

func save(_ img: CGImage, _ url: URL) {
  try? FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
  let dest = CGImageDestinationCreateWithURL(url as CFURL, UTType.png.identifier as CFString, 1, nil)!
  CGImageDestinationAddImage(dest, img, nil)
  guard CGImageDestinationFinalize(dest) else { fatalError("could not write \(url.path)") }
  print("wrote \(url.path.replacingOccurrences(of: root.path + "/", with: "")) (\(img.width)x\(img.height))")
}

for (density, px) in [("mdpi", 48), ("hdpi", 72), ("xhdpi", 96), ("xxhdpi", 144), ("xxxhdpi", 192)] {
  let dir = res.appendingPathComponent("mipmap-\(density)")
  save(render(size: px, crop: 72, mask: .roundedSquare, opaque: false), dir.appendingPathComponent("ic_launcher.png"))
  save(render(size: px, crop: 72, mask: .circle, opaque: false), dir.appendingPathComponent("ic_launcher_round.png"))
}
// Play Store icon: full square (Google applies its own mask), 512x512, 32-bit PNG WITH an alpha channel as Play asks
// (v3.1.1, audit C5); every pixel is opaque because the background fills the whole square.
save(render(size: 512, crop: 72, mask: .none, opaque: false), play.appendingPathComponent("icon-512.png"))
// Large opaque copy, used by scripts/make-store-assets.swift for the feature graphic.
save(render(size: 1024, crop: 72, mask: .none, opaque: true), play.appendingPathComponent("icon-1024.png"))
