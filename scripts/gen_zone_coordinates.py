#!/usr/bin/env python3
"""Generates app/src/main/java/com/tim/dimmer/engine/ZoneCoordinates.kt from IANA zone.tab.

zone.tab (public domain, shipped with macOS at /usr/share/zoneinfo/zone.tab) lists one principal
location per time-zone ID. Dimmer uses it to compute sunset/sunrise without location permission
(D-V3-04). Run from the repo root:

    python3 scripts/gen_zone_coordinates.py [path/to/zone.tab]

The output is committed; re-run only to refresh the table.
"""
import os
import re
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/zoneinfo/zone.tab"
OUT = os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    "..", "app", "src", "main", "java", "com", "tim", "dimmer", "engine", "ZoneCoordinates.kt",
)

COORD = re.compile(r"^([+-])(\d{2})(\d{2})(\d{2})?([+-])(\d{3})(\d{2})(\d{2})?$")


def parse(coord):
    m = COORD.match(coord)
    if not m:
        raise ValueError("bad coordinates: " + coord)
    lat = int(m.group(2)) + int(m.group(3)) / 60 + int(m.group(4) or 0) / 3600
    lon = int(m.group(6)) + int(m.group(7)) / 60 + int(m.group(8) or 0) / 3600
    if m.group(1) == "-":
        lat = -lat
    if m.group(5) == "-":
        lon = -lon
    return round(lat, 4), round(lon, 4)


def main():
    rows = []
    with open(SRC, encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            parts = line.rstrip("\n").split("\t")
            lat, lon = parse(parts[1])
            rows.append((parts[2], lat, lon))
    rows.sort()
    body = "\n".join("%s %s %s" % (tz, lat, lon) for tz, lat, lon in rows)
    kt = f'''package com.plainapps.dimmer.engine

// GENERATED by scripts/gen_zone_coordinates.py from {SRC} ({len(rows)} zones).
// Do not edit by hand. Source: IANA tz database zone.tab (public domain).

/** Principal location (latitude, longitude in degrees) of every IANA time-zone ID in zone.tab. */
internal object ZoneCoordinates {{
    const val COUNT = {len(rows)}

    /** One line per zone: "ID latitude longitude". */
    val TABLE: String = """
{body}
""".trimIndent()
}}
'''
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(kt)
    print("wrote %d zones to %s" % (len(rows), os.path.normpath(OUT)))


if __name__ == "__main__":
    main()
